func TestSprintf(t *testing.T) {
	for _, c := range printfCases {
		var got string
		switch c.kind {
		case "f":
			bits, _ := strconv.ParseUint(c.arg, 0, 64)
			got = SprintfFloat(c.spec, math.Float64frombits(bits))
		case "i":
			v, _ := strconv.ParseInt(c.arg, 10, 64)
			got = SprintfInt(c.spec, v)
		case "u":
			v, _ := strconv.ParseUint(c.arg, 10, 64)
			got = SprintfUint(c.spec, v)
		case "c":
			v, _ := strconv.Atoi(c.arg)
			got = SprintfChar(c.spec, v)
		case "s":
			got = SprintfString(c.spec, c.arg)
		}
		if got != c.want {
			t.Errorf("%s %q %s: got %q, want %q", c.kind, c.spec, c.arg, got, c.want)
		}
	}
}

