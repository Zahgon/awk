func TestRandom(t *testing.T) {
	cases := []struct {
		seed  uint32
		fresh bool
		want  []int32
	}{
		{1, true, []int32{1804289383, 846930886, 1681692777, 1714636915, 1957747793, 424238335}},
		{0, false, []int32{1804289383, 846930886, 1681692777}},
		{42, false, []int32{71876166, 708592740, 1483128881, 907283241, 442951012}},
		{4294967295, false, []int32{254925627, 1205188300, 366127624, 1401405153, 76053476}},
	}
	for _, c := range cases {
		var g Random
		if !c.fresh {
			g.Seed(c.seed)
		}
		for i, want := range c.want {
			if got := g.Next(); got != want {
				t.Errorf("seed %d: value %d = %d, want %d", c.seed, i, got, want)
			}
		}
	}
}

func TestMultibyte(t *testing.T) {
	decode := []struct {
		in string
		r  rune
		n  int
	}{
		{"", 0, 0}, {"A", 'A', 1}, {"\xc3\xa9", 0xE9, 2}, {"\xe2\x82\xac", 0x20AC, 3}, {"\xf4\x8f\xbf\xbf", 0x10FFFF, 4},
		{"\xf4\x90\x80\x80", 0x110000, 4}, {"\xf8\x88\x80\x80\x80", 0x200000, 5},
		{"\xfc\x84\x80\x80\x80\x80", 0x4000000, 6}, {"\xed\xa0\x80", 0, -1}, {"\xc0\x80", 0, -1},
		{"\xe0\x80\x80", 0, -1}, {"\xc3", 0, -1}, {"\x80", 0, -1}, {"\xff", 0, -1}, {"\xc3(", 0, -1},
	}
	for _, c := range decode {
		if r, n := DecodeMB(c.in); r != c.r || n != c.n {
			t.Errorf("DecodeMB(%q) = %#x, %d; want %#x, %d", c.in, r, n, c.r, c.n)
		}
	}
	encode := []struct {
		r    rune
		want string
		ok   bool
	}{
		{'A', "A", true}, {0xE9, "\xc3\xa9", true}, {0xD800, "", false}, {0xFFFE, "\xef\xbf\xbe", true},
		{0x110000, "\xf4\x90\x80\x80", true}, {0x7FFFFFFF, "\xfd\xbf\xbf\xbf\xbf\xbf", true}, {-1, "", false},
	}
	for _, c := range encode {
		if got, ok := EncodeMB(c.r); got != c.want || ok != c.ok {
			t.Errorf("EncodeMB(%#x) = %q, %v; want %q, %v", c.r, got, ok, c.want, c.ok)
		}
	}
	for _, c := range []struct{ r, up, low rune }{{'a', 'A', 'a'}, {0xDF, 0xDF, 0xDF}, {0x1E9E, 0x1E9E, 0xDF},
		{0x1C5, 0x1C4, 0x1C6}, {0x3C3, 0x3A3, 0x3C3}, {0x110000, 0x110000, 0x110000}} {
		if up, low := ToUpper(c.r), ToLower(c.r); up != c.up || low != c.low {
			t.Errorf("case of %#x = %#x, %#x; want %#x, %#x", c.r, up, low, c.up, c.low)
		}
	}
}
